import { decodeNeuronIndex } from '@/core/binary';
import { DataError } from '@/core/errors';
import { asLoreId, type LoreId } from '@/core/ids';
import { voxelToMicrometres } from '@/core/coords';
import type { BrainDatasetAdapter, NeuronIndexOptions } from '@/core/adapter';
import {
  cellTypeFromCode,
  type ConnectionPartner,
  type ConnectionQuery,
  type ConnectionSet,
  type DataOrigin,
  type DatasetMetadata,
  type DatasetVersion,
  type Neuron,
  type NeuronIndex,
  type SearchResult,
  TRAVERSAL_LIMITS,
} from '@/core/types';
import { SYNTHETIC_VOXEL_SPACE, syntheticPartners } from './generator';
import type {
  PopulationWorkerResponse,
  GeneratePopulationRequest,
} from '@/workers/population.worker';

/**
 * Synthetic dataset adapter.
 *
 * Serves two roles:
 *  - SYNTHETIC BENCHMARK: deterministic populations at chosen sizes, used to
 *    measure renderer performance without repeatedly downloading real data.
 *  - DEVELOPMENT SAMPLE: a schema-complete stand-in so the application is
 *    usable before a Fish1 export exists.
 *
 * Both are badged in the UI and neither contains any biological measurement.
 * The only difference between them is the `origin` reported in metadata, which
 * is what drives that badge.
 */
export class SyntheticAdapter implements BrainDatasetAdapter {
  readonly id: string;

  private index: NeuronIndex | null = null;
  private worker: Worker | null = null;
  private nextRequestId = 1;
  private lastGenerateMs = 0;

  constructor(
    private readonly config: {
      id: string;
      title: string;
      count: number;
      seed: number;
      origin: Extract<DataOrigin, 'development-sample' | 'synthetic-benchmark'>;
    },
  ) {
    this.id = config.id;
  }

  private version(): DatasetVersion {
    return {
      materializationVersion: null,
      generatedAt: undefined,
      label: `synthetic seed ${this.config.seed} / n=${this.config.count}`,
    };
  }

  async metadata(): Promise<DatasetMetadata> {
    const isBenchmark = this.config.origin === 'synthetic-benchmark';
    return {
      id: this.id,
      title: this.config.title,
      organism: 'None (procedurally generated)',
      description: isBenchmark
        ? 'Deterministic synthetic population generated in-browser to measure rendering performance. Contains no biological data.'
        : 'Schema-complete synthetic stand-in used while no real dataset export is present. Contains no biological data.',
      modality: ['structural'],
      origin: this.config.origin,
      capabilities: {
        neuronIndex: true,
        neuronMetadata: true,
        connectivity: true,
        skeletons: false,
        synapsePositions: false,
        regions: true,
        activity: false,
        search: true,
        downloads: true,
      },
      voxelSpace: SYNTHETIC_VOXEL_SPACE,
      published: { somaCount: this.config.count },
      version: this.version(),
      license: 'Generated by this application. No third-party data.',
    };
  }

  async neuronIndex(options?: NeuronIndexOptions): Promise<NeuronIndex> {
    options?.onProgress?.({
      stage: 'downloading',
      fraction: null,
      message: `GENERATING ${this.config.count.toLocaleString()} SYNTHETIC SOMA`,
    });

    const buffer = await this.generate(options?.signal);

    options?.onProgress?.({
      stage: 'decoding',
      fraction: null,
      message: 'DECODING NEURON INDEX',
      bytesTotal: buffer.byteLength,
      bytesLoaded: buffer.byteLength,
    });

    const index = decodeNeuronIndex(buffer);
    this.index = index;
    return index;
  }

  /** Wall-clock time the worker spent generating, for the benchmark readout. */
  generationTimeMs(): number {
    return this.lastGenerateMs;
  }

  private ensureWorker(): Worker {
    if (!this.worker) {
      this.worker = new Worker(new URL('@/workers/population.worker.ts', import.meta.url), {
        type: 'module',
      });
    }
    return this.worker;
  }

  private generate(signal?: AbortSignal): Promise<ArrayBuffer> {
    const worker = this.ensureWorker();
    const requestId = this.nextRequestId++;

    return new Promise<ArrayBuffer>((resolve, reject) => {
      const onMessage = (event: MessageEvent<PopulationWorkerResponse>) => {
        const data = event.data;
        if (data.requestId !== requestId) return;
        cleanup();
        if (data.type === 'error') {
          reject(new DataError({ code: 'unknown', message: data.message, datasetId: this.id }));
          return;
        }
        this.lastGenerateMs = data.generateMs;
        resolve(data.buffer);
      };
      const onError = (event: ErrorEvent) => {
        cleanup();
        reject(
          new DataError({
            code: 'unknown',
            message: `Population worker failed: ${event.message}`,
            datasetId: this.id,
          }),
        );
      };
      const onAbort = () => {
        cleanup();
        reject(new DataError({ code: 'timeout', message: 'Generation aborted.' }));
      };
      const cleanup = () => {
        worker.removeEventListener('message', onMessage);
        worker.removeEventListener('error', onError);
        signal?.removeEventListener('abort', onAbort);
      };

      worker.addEventListener('message', onMessage);
      worker.addEventListener('error', onError);
      signal?.addEventListener('abort', onAbort);

      const request: GeneratePopulationRequest = {
        type: 'generate',
        requestId,
        count: this.config.count,
        seed: this.config.seed,
        datasetId: this.id,
        origin: this.config.origin,
        version: this.version(),
      };
      worker.postMessage(request);
    });
  }

  private requireIndex(): NeuronIndex {
    if (!this.index) {
      throw new DataError({
        code: 'not_found',
        message: 'The synthetic population has not been generated yet.',
        datasetId: this.id,
      });
    }
    return this.index;
  }

  private indexOfLoreId(loreId: LoreId): number {
    const index = this.requireIndex();
    const target = Number(loreId);
    // Synthetic lore IDs are assigned sequentially, so this is O(1).
    const guess = target - index.loreIds[0];
    if (guess >= 0 && guess < index.count && index.loreIds[guess] === target) return guess;
    for (let i = 0; i < index.count; i++) {
      if (index.loreIds[i] === target) return i;
    }
    return -1;
  }

  async getNeuron(loreId: LoreId): Promise<Neuron> {
    const index = this.requireIndex();
    const i = this.indexOfLoreId(loreId);
    if (i < 0) {
      throw new DataError({
        code: 'not_found',
        message: `No synthetic neuron with lore ID ${loreId}.`,
        datasetId: this.id,
      });
    }
    const voxel: [number, number, number] = [
      index.positionsVoxel[i * 3],
      index.positionsVoxel[i * 3 + 1],
      index.positionsVoxel[i * 3 + 2],
    ];
    const region = index.regions[index.regionIds[i]];
    return {
      datasetId: this.id,
      loreId,
      root: null,
      cellType: cellTypeFromCode(index.cellTypes[i]),
      positionVoxel: voxel,
      positionUm: voxelToMicrometres(voxel, index.voxelSpace),
      regionId: region?.id,
      flags: index.flags[i],
      annotations: {
        note: 'Synthetic neuron. Not a biological observation.',
      },
      // The strongest honest label for generated data.
      provenance: 'simulated',
    };
  }

  async getConnections(loreId: LoreId, query?: ConnectionQuery): Promise<ConnectionSet> {
    const index = this.requireIndex();
    const i = this.indexOfLoreId(loreId);
    if (i < 0) {
      throw new DataError({
        code: 'not_found',
        message: `No synthetic neuron with lore ID ${loreId}.`,
        datasetId: this.id,
      });
    }

    const minSynapses = query?.minSynapses ?? 1;
    const topN = Math.min(query?.topN ?? 50, TRAVERSAL_LIMITS.maxPartnersPerHop);
    const direction = query?.direction ?? 'both';

    const partners: ConnectionPartner[] = [];
    const totals = {
      incomingSynapses: 0,
      outgoingSynapses: 0,
      incomingPartners: 0,
      outgoingPartners: 0,
      incomingExcitatory: 0,
      incomingInhibitory: 0,
      outgoingExcitatory: 0,
      outgoingInhibitory: 0,
    };

    const collect = (dir: 'incoming' | 'outgoing') => {
      const raw = syntheticPartners(i, index.count, dir);
      for (const p of raw) {
        const polarity = cellTypeFromCode(index.cellTypes[p.index]);
        if (dir === 'incoming') {
          totals.incomingSynapses += p.synapseCount;
          totals.incomingPartners++;
          if (polarity === 'excitatory') totals.incomingExcitatory += p.synapseCount;
          if (polarity === 'inhibitory') totals.incomingInhibitory += p.synapseCount;
        } else {
          totals.outgoingSynapses += p.synapseCount;
          totals.outgoingPartners++;
          if (polarity === 'excitatory') totals.outgoingExcitatory += p.synapseCount;
          if (polarity === 'inhibitory') totals.outgoingInhibitory += p.synapseCount;
        }
      }
      return raw
        .filter((p) => p.synapseCount >= minSynapses)
        .slice(0, topN)
        .map<ConnectionPartner>((p) => ({
          loreId: asLoreId(index.loreIds[p.index]),
          rootId: null,
          direction: dir,
          synapseCount: p.synapseCount,
          partnerCellType: cellTypeFromCode(index.cellTypes[p.index]),
          depth: 1,
        }));
    };

    if (direction === 'incoming' || direction === 'both') partners.push(...collect('incoming'));
    if (direction === 'outgoing' || direction === 'both') partners.push(...collect('outgoing'));

    return {
      datasetId: this.id,
      loreId,
      rootId: null,
      version: this.version(),
      partners,
      totals,
      truncated: false,
      // Generated, not observed, and labelled as such everywhere it is shown.
      provenance: 'simulated',
    };
  }

  async search(term: string): Promise<SearchResult[]> {
    const index = this.requireIndex();
    const trimmed = term.trim();
    if (!/^\d+$/.test(trimmed)) return [];

    const results: SearchResult[] = [];
    const exact = this.indexOfLoreId(asLoreId(trimmed));
    if (exact >= 0) {
      results.push({
        datasetId: this.id,
        loreId: asLoreId(index.loreIds[exact]),
        label: String(index.loreIds[exact]),
        sublabel: index.regions[index.regionIds[exact]]?.name,
        cellType: cellTypeFromCode(index.cellTypes[exact]),
        matchedOn: 'lore-id',
      });
    }

    // Prefix matches, capped so a short query cannot return a huge list.
    for (let i = 0; i < index.count && results.length < 20; i++) {
      if (i === exact) continue;
      if (String(index.loreIds[i]).startsWith(trimmed)) {
        results.push({
          datasetId: this.id,
          loreId: asLoreId(index.loreIds[i]),
          label: String(index.loreIds[i]),
          sublabel: index.regions[index.regionIds[i]]?.name,
          cellType: cellTypeFromCode(index.cellTypes[i]),
          matchedOn: 'lore-id',
        });
      }
    }
    return results;
  }

  dispose(): void {
    this.worker?.terminate();
    this.worker = null;
  }
}

/** Benchmark population sizes offered in the developer benchmark control. */
export const BENCHMARK_SIZES = [10_000, 50_000, 100_000, 200_000, 500_000] as const;

export function createBenchmarkAdapter(count: number, seed = 20250610): SyntheticAdapter {
  return new SyntheticAdapter({
    // MUST match the registry key (see registry.ts), otherwise the dataset
    // picker cannot match it to an <option> and silently displays a different
    // dataset's name over synthetic data.
    id: `benchmark-${count}`,
    title: `Synthetic benchmark (${count.toLocaleString()} soma)`,
    count,
    seed,
    origin: 'synthetic-benchmark',
  });
}

export function createDevSampleAdapter(count = 180_000, seed = 7): SyntheticAdapter {
  return new SyntheticAdapter({
    id: 'dev-sample',
    title: 'Development sample',
    count,
    seed,
    origin: 'development-sample',
  });
}
